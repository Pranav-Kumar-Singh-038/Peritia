export const SKILL_BY_ID = Object.fromEntries(SKILLS.map((skill) => [skill.id, skill])) as Record<
  SkillId,
  SkillSeed
>;

export function createSkillStates(): SkillState[] {
  return SKILLS.map((seed) => ({
    ...seed,
    metrics: seed.metrics.map((m) => ({ ...m, rubric: { ...m.rubric } })),
    level: 0,
    certifiedLevel: 0,
    xp: 0,
    assessedAt: null,
    scores: null,
  }));
}

export function skillSeed(id: SkillId): SkillSeed {
  return SKILL_BY_ID[id];
}
